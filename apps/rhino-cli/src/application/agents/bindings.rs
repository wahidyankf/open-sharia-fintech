/// Relative path (from repo root) of the platform-bindings catalog document.
pub const PLATFORM_BINDINGS_CATALOG: &str = "docs/reference/platform-bindings.md";

/// One canonical (relative path, expected content) pair for a generated file.
#[derive(Debug, Clone)]
pub struct BindingFile {
    /// POSIX-style path relative to the repository root (e.g. `.amazonq/rules/00-agents-md.md`).
    pub rel_path: String,
    /// Exact byte content the file must contain.
    pub content: String,
}

/// Single source of truth for both `emit_bindings` and `validate_bindings`.
/// Returns the Amazon Q agent name declared in the repository configuration.
fn amazonq_agent_name(repo_root: &Path) -> Result<String, String> {
    let config = repo_config::load(repo_root)
        .map_err(|error| format!("load repo-config.yml for Amazon Q bindings: {error:#}"))?;
    config
        .harness
        .iter()
        .find(|entry| entry.name == "amazonq")
        .and_then(|entry| entry.agent_name.clone())
        .filter(|name| is_kebab_case_identifier(name))
        .ok_or_else(|| {
            "harness.amazonq.agent-name must be a non-empty lowercase kebab-case identifier"
                .to_string()
        })
}

/// Returns `true` when `value` is safe to embed in the generated agent file
/// name and JSON string without adding repository-specific escaping rules.
fn is_kebab_case_identifier(value: &str) -> bool {
    !value.is_empty()
        && !value.starts_with('-')
        && !value.ends_with('-')
        && value
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
}

/// Builds deterministic Amazon Q definition JSON for `agent_name` (2-space
/// indent and trailing newline) so byte-equality stays stable across emit and
/// validate.
fn agent_definition_content(agent_name: &str) -> String {
    format!(
        "{{\n  \"name\": \"{agent_name}\",\n  \"description\": \"Loads the repository's canonical AGENTS.md instructions and project rules.\",\n  \"prompt\": \"Follow the canonical repository instructions in AGENTS.md and the rules in .amazonq/rules/.\",\n  \"resources\": [\n    \"file://AGENTS.md\",\n    \"file://.amazonq/rules/**/*.md\"\n  ],\n  \"tools\": [\n    \"*\"\n  ]\n}}\n"
    )
}

/// Returns the canonical relative paths and exact byte content of every bridge
/// file. The Amazon Q definition name is repository data read from
/// `harness.amazonq.agent-name`; the validator stays in lock-step with the
/// emitter because both read these pairs.
///
/// # Errors
///
/// Returns an error when the repository configuration cannot supply a valid
/// Amazon Q agent definition name.
pub fn expected_bindings(repo_root: &Path) -> Result<Vec<BindingFile>, String> {
    let agent_name = amazonq_agent_name(repo_root)?;
    let agent_definition_path = format!("{AMAZONQ_AGENT_DEFINITION_DIR}/{agent_name}.json");
    Ok(vec![
        BindingFile {
            rel_path: AMAZONQ_RULES_POINTER.to_string(),
            content: RULES_POINTER_CONTENT.to_string(),
        },
        BindingFile {
            rel_path: agent_definition_path,
            content: agent_definition_content(&agent_name),
        },
    ])
}

/// Result of emitting the bridge files.
#[derive(Debug, Clone, Default)]
pub struct EmitResult {
    /// Relative paths of the files that were written.
    pub written: Vec<String>,
    /// Wall time for the emit operation.
    pub duration: std::time::Duration,
}

/// Writes every bridge file under `repo_root` with its deterministic content,
/// creating parent directories as needed. Idempotent: overwrites existing
/// files with the canonical bytes.
///
/// # Errors
///
/// Returns an error string if a directory cannot be created or a file cannot
/// be written.
pub fn emit_bindings(repo_root: &Path) -> Result<EmitResult, String> {
    #[cfg(unix)]
    {
        emit_bindings_no_follow(repo_root)
    }

    #[cfg(not(unix))]
    {
        emit_bindings_with_metadata_checks(repo_root)
    }
}

/// Emit Amazon Q bindings through directory descriptors, so each path lookup
/// is anchored to the repository and rejects symlinks at the kernel boundary.
/// This prevents an attacker from replacing a checked path with a symlink
/// between inspection and write or stale-definition cleanup.
#[cfg(unix)]
fn emit_bindings_no_follow(repo_root: &Path) -> Result<EmitResult, String> {
    let start = Instant::now();
    let mut result = EmitResult::default();
    let bindings = expected_bindings(repo_root)?;
    let agent_name = amazonq_agent_name(repo_root)?;
    let root = open_repository_directory(repo_root)?;
    let amazonq = open_or_create_directory(&root, ".amazonq")?;
    let rules = open_or_create_directory(&amazonq, "rules")?;
    let definitions = open_or_create_directory(&amazonq, "cli-agents")?;

    write_no_follow_file(&rules, "00-agents-md.md", &bindings[0].content)?;
    write_no_follow_file(
        &definitions,
        &format!("{agent_name}.json"),
        &bindings[1].content,
    )?;
    result.written = bindings
        .into_iter()
        .map(|binding| binding.rel_path)
        .collect();

    remove_stale_amazonq_definitions_no_follow(&definitions, &agent_name)?;

    result.duration = start.elapsed();
    Ok(result)
}

/// Open the configured repository root as a directory without following a
/// final symlink. Every subsequent lookup is descriptor-relative.
#[cfg(unix)]
fn open_repository_directory(repo_root: &Path) -> Result<OwnedFd, String> {
    use rustix::fs::{CWD, Mode, OFlags, openat};

    openat(
        CWD,
        repo_root,
        OFlags::RDONLY | OFlags::DIRECTORY | OFlags::NOFOLLOW | OFlags::CLOEXEC,
        Mode::empty(),
    )
    .map_err(|error| {
        format!(
            "failed to open repository root {} with symlink protection: {error}",
            repo_root.display()
        )
    })
}

/// Obtain a child directory from a trusted parent descriptor, creating it if
/// absent. A concurrent symlink replacement is rejected by the final
/// descriptor-relative `openat` with `O_NOFOLLOW`.
#[cfg(unix)]
fn open_or_create_directory(parent: &OwnedFd, name: &str) -> Result<OwnedFd, String> {
    use rustix::fs::{Mode, OFlags, mkdirat, openat};
    use rustix::io::Errno;

    let flags = OFlags::RDONLY | OFlags::DIRECTORY | OFlags::NOFOLLOW | OFlags::CLOEXEC;
    match openat(parent, name, flags, Mode::empty()) {
        Ok(directory) => Ok(directory),
        Err(Errno::NOENT) => {
            if let Err(error) = mkdirat(parent, name, Mode::RWXU)
                && error != Errno::EXIST
            {
                return Err(format!(
                    "failed to create Amazon Q binding directory {name} with symlink protection: {error}"
                ));
            }
            openat(parent, name, flags, Mode::empty()).map_err(|error| {
                format!(
                    "failed to open Amazon Q binding directory {name} with symlink protection: {error}"
                )
            })
        }
        Err(error) => Err(format!(
            "failed to open Amazon Q binding directory {name} with symlink protection: {error}"
        )),
    }
}

/// Write a generated file through its parent directory descriptor without
/// resolving a symlink at the final path component.
#[cfg(unix)]
fn write_no_follow_file(parent: &OwnedFd, name: &str, content: &str) -> Result<(), String> {
    use rustix::fs::{Mode, OFlags, openat};

    let file = openat(
        parent,
        name,
        OFlags::WRONLY | OFlags::CREATE | OFlags::TRUNC | OFlags::NOFOLLOW | OFlags::CLOEXEC,
        Mode::RUSR | Mode::WUSR,
    )
    .map_err(|error| {
        format!("failed to open Amazon Q binding file {name} with symlink protection: {error}")
    })?;
    std::fs::File::from(file)
        .write_all(content.as_bytes())
        .map_err(|error| format!("failed to write Amazon Q binding file {name}: {error}"))
}

/// Remove obsolete generated definitions through the trusted definitions
/// directory descriptor. Both inspection and deletion are descriptor-relative
/// and no-follow, so a concurrent path swap cannot delete outside the repo.
#[cfg(unix)]
fn remove_stale_amazonq_definitions_no_follow(
    definitions_dir: &OwnedFd,
    expected_name: &str,
) -> Result<(), String> {
    use rustix::fs::{AtFlags, Dir, unlinkat};

    let expected_file = format!("{expected_name}.json");
    let entries = Dir::read_from(definitions_dir).map_err(|error| {
        format!("failed to list generated Amazon Q definitions safely: {error}")
    })?;
    for entry in entries {
        let entry = entry.map_err(|error| {
            format!("failed to inspect generated Amazon Q definition safely: {error}")
        })?;
        let Ok(file_name) = entry.file_name().to_str() else {
            continue;
        };
        if file_name == expected_file
            || !is_emitter_managed_definition_at(definitions_dir, file_name)
        {
            continue;
        }
        unlinkat(definitions_dir, file_name, AtFlags::empty()).map_err(|error| {
            format!("failed to remove stale generated Amazon Q definition {file_name}: {error}")
        })?;
    }
    Ok(())
}

/// Return whether a descriptor-relative candidate is a regular file whose
/// bytes exactly match a definition that this emitter could have generated.
#[cfg(unix)]
fn is_emitter_managed_definition_at(definitions_dir: &OwnedFd, file_name: &str) -> bool {
    use rustix::fs::{Mode, OFlags, openat};

    let Some(agent_name) = file_name.strip_suffix(".json") else {
        return false;
    };
    if !is_kebab_case_identifier(agent_name) {
        return false;
    }
    let Ok(file) = openat(
        definitions_dir,
        file_name,
        OFlags::RDONLY | OFlags::NOFOLLOW | OFlags::CLOEXEC,
        Mode::empty(),
    ) else {
        return false;
    };
    let mut content = String::new();
    let mut file = std::fs::File::from(file);
    file.metadata().is_ok_and(|metadata| metadata.is_file())
        && file.read_to_string(&mut content).is_ok()
        && content == agent_definition_content(agent_name)
}

/// Fallback emitter for platforms without POSIX descriptor-relative APIs.
/// Unix targets use [`emit_bindings_no_follow`] instead.
#[cfg(not(unix))]
fn emit_bindings_with_metadata_checks(repo_root: &Path) -> Result<EmitResult, String> {
    let start = Instant::now();
    let mut result = EmitResult::default();

    for binding in expected_bindings(repo_root)? {
        reject_symlinked_binding_path(repo_root, &binding.rel_path)?;
        let abs = join_rel(repo_root, &binding.rel_path);
        if let Some(parent) = abs.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| format!("failed to create directory {}: {e}", parent.display()))?;
        }
        reject_symlinked_binding_path(repo_root, &binding.rel_path)?;
        fs::write(&abs, binding.content)
            .map_err(|e| format!("failed to write {}: {e}", abs.display()))?;
        result.written.push(binding.rel_path);
    }

    remove_stale_amazonq_definitions(repo_root)?;

    result.duration = start.elapsed();
    Ok(result)
}

/// Remove obsolete generated Amazon Q agent definitions after a configured
/// `harness.amazonq.agent-name` rename. The definitions directory can also
/// contain custom Amazon Q agents, so a candidate is removed only when its
/// file name and exact contents prove that a previous emitter run generated it.
#[cfg(not(unix))]
fn remove_stale_amazonq_definitions(repo_root: &Path) -> Result<(), String> {
    let expected_name = amazonq_agent_name(repo_root)?;
    let expected_file = format!("{expected_name}.json");
    reject_symlinked_binding_path(repo_root, AMAZONQ_AGENT_DEFINITION_DIR)?;
    let definitions_dir = repo_root.join(AMAZONQ_AGENT_DEFINITION_DIR);
    let entries = fs::read_dir(&definitions_dir).map_err(|error| {
        format!(
            "failed to list generated Amazon Q definitions at {}: {error}",
            definitions_dir.display()
        )
    })?;
    for entry in entries {
        let entry = entry.map_err(|error| {
            format!(
                "failed to inspect generated Amazon Q definition at {}: {error}",
                definitions_dir.display()
            )
        })?;
        let path = entry.path();
        let is_expected = path.file_name().and_then(|name| name.to_str()) == Some(&expected_file);
        if !is_expected && is_emitter_managed_definition(&entry) {
            fs::remove_file(&path).map_err(|error| {
                format!(
                    "failed to remove stale generated Amazon Q definition {}: {error}",
                    path.display()
                )
            })?;
        }
    }
    Ok(())
}

/// Refuse an Amazon Q binding path when an existing component is a symlink.
///
/// Emission and stale-definition cleanup must never traverse a repository path
/// that has been redirected outside the repository. The binding paths are
/// fixed relative paths, so checking each component protects both directory
/// creation and file writes without accepting user-supplied path traversal.
#[cfg(not(unix))]
fn reject_symlinked_binding_path(repo_root: &Path, rel_path: &str) -> Result<(), String> {
    let mut path = repo_root.to_path_buf();
    for segment in rel_path.split('/') {
        if segment.is_empty() {
            continue;
        }
        path.push(segment);
        match fs::symlink_metadata(&path) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(format!(
                    "refusing Amazon Q binding path {} because {} is a symlink",
                    rel_path,
                    path.display()
                ));
            }
            Ok(_) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => {
                return Err(format!(
                    "failed to inspect Amazon Q binding path {}: {error}",
                    path.display()
                ));
            }
        }
    }
    Ok(())
}

/// Returns whether `entry` is a regular file whose name and exact bytes match
/// a definition that this emitter could have generated. Failed reads and
/// non-regular entries are deliberately treated as unmanaged: cleanup must
/// preserve anything it cannot positively identify as an emitted definition.
#[cfg(not(unix))]
fn is_emitter_managed_definition(entry: &fs::DirEntry) -> bool {
    let Ok(file_type) = entry.file_type() else {
        return false;
    };
    if !file_type.is_file() {
        return false;
    }

    let Some(file_name) = entry.file_name().to_str().map(str::to_owned) else {
        return false;
    };
    let Some(agent_name) = file_name.strip_suffix(".json") else {
        return false;
    };
    if !is_kebab_case_identifier(agent_name) {
        return false;
    }

    fs::read_to_string(entry.path())
        .is_ok_and(|content| content == agent_definition_content(agent_name))
}

/// Validates all 11 harnesses:
/// - Amazon Q bridge files: byte-for-byte parity with `expected_bindings(repo_root)`
/// - `OpenCode` mirror: `.opencode/agents/` mirrors `.claude/agents/` (via `validate_sync`)
/// - Cursor mirror: `.cursor/agents/` mirrors `.claude/agents/` (via `validate_cursor_sync`)
/// - Catalog coverage: every present binding dir referenced in the platform-bindings doc
/// - No-Codex-agents-dir: `.codex/agents/` must not exist (Codex reads AGENTS.md natively)
/// - Color/tier translation maps: every `color:` and `model:` value in `.claude/agents/*.md`
///   resolves in the governance docs (ported from `validate-cross-vendor-parity.sh` §5a/5b)
#[must_use]
pub fn validate_bindings(repo_root: &Path) -> ValidationResult {
    let start = Instant::now();
    let mut result = ValidationResult::default();

    // Amazon Q bridge files (byte-parity with their configured definition name).
    match expected_bindings(repo_root) {
        Ok(bindings) => {
            for binding in &bindings {
                result.tally(validate_binding_file(repo_root, binding));
            }
        }
        Err(error) => result.tally(ValidationCheck::failed_msg(
            "Amazon Q binding configuration",
            error,
        )),
    }

    // OpenCode agent mirror parity (.claude/ ↔ .opencode/)
    let sync_result = validate_sync(repo_root);
    for check in sync_result.checks {
        result.tally(check);
    }

    // Cursor agent mirror parity (.claude/ ↔ .cursor/agents/)
    let cursor_result = validate_cursor_sync(repo_root);
    for check in cursor_result.checks {
        result.tally(check);
    }

    // Catalog coverage for every present known binding dir / file
    for dir in KNOWN_BINDING_DIRS {
        result.tally(validate_catalog_coverage(repo_root, dir));
    }

    result.tally(validate_no_codex_agents_dir(repo_root));

    // Color/tier translation-map coverage (absorbed from validate-cross-vendor-parity.sh §5a/5b)
    for check in validate_color_tier_maps(repo_root) {
        result.tally(check);
    }

    result.duration = start.elapsed();
    result
}

/// Reads `path`'s content, plus (per the Split Pattern) the content of every
/// `.md` child in its sibling split directory (`<parent>/<stem>/*.md`), when
/// one exists. Governance docs relocate table content into split children
/// while the parent keeps only a trimmed index, so a lookup scoped to the
/// parent file alone would miss relocated tables.
fn read_with_split_children(path: &Path) -> String {
    let mut content = fs::read_to_string(path).unwrap_or_default();
    if let Some(stem) = path.file_stem().and_then(|s| s.to_str())
        && let Some(parent) = path.parent()
    {
        let split_dir = parent.join(stem);
        if let Ok(entries) = fs::read_dir(&split_dir) {
            let mut children: Vec<_> = entries
                .flatten()
                .map(|e| e.path())
                .filter(|p| p.extension().and_then(|e| e.to_str()) == Some("md"))
                .collect();
            children.sort();
            for child in children {
                if let Ok(child_content) = fs::read_to_string(&child) {
                    content.push('\n');
                    content.push_str(&child_content);
                }
            }
        }
    }
    content
}

/// Validates that every `color:` and `model:` value used in `.claude/agents/*.md`
/// resolves in the governance translation-map documents (§5a/5b of the
/// cross-vendor parity invariant).
///
/// Returns an empty vec when the agents directory does not exist (nothing to check).
#[allow(clippy::too_many_lines)]
fn validate_color_tier_maps(repo_root: &Path) -> Vec<ValidationCheck> {
    let agents_dir = repo_root.join(".claude").join("agents");
    if !agents_dir.is_dir() {
        return vec![];
    }

    let color_map_path = repo_root.join("repo-governance/development/agents/ai-agents.md");
    let tier_map_path = repo_root.join("repo-governance/development/agents/model-selection.md");

    let color_map = read_with_split_children(&color_map_path);
    let tier_map = read_with_split_children(&tier_map_path);

    let mut checks = Vec::new();
    let mut seen_colors = std::collections::BTreeSet::new();
    let mut seen_tiers = std::collections::BTreeSet::new();

    let Ok(entries) = fs::read_dir(&agents_dir) else {
        return vec![];
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("md") {
            continue;
        }
        let Ok(content) = fs::read_to_string(&path) else {
            continue;
        };
        for line in content.lines() {
            if let Some(color) = line.strip_prefix("color:").map(str::trim)
                && !color.is_empty()
            {
                seen_colors.insert(color.to_string());
            }
            if let Some(model) = line.strip_prefix("model:").map(str::trim)
                && !model.is_empty()
            {
                seen_tiers.insert(model.to_string());
            }
        }
    }

    // §5a: color translation map
    let opencode_direct = [
        "primary",
        "success",
        "warning",
        "secondary",
        "error",
        "info",
        "accent",
        "muted",
    ];
    for color in &seen_colors {
        if opencode_direct.contains(&color.as_str()) {
            checks.push(ValidationCheck::passed(
                format!("Color translation: {color}"),
                format!("'{color}' is a valid OpenCode theme token (no mapping needed)"),
            ));
            continue;
        }
        if color_map.contains(&format!("`{color}`")) {
            checks.push(ValidationCheck::passed(
                format!("Color translation: {color}"),
                format!("'{color}' is mapped in ai-agents.md"),
            ));
        } else {
            checks.push(ValidationCheck::failed(
                format!("Color translation: {color}"),
                "color mapped in repo-governance/development/agents/ai-agents.md",
                format!("'{color}' is NOT in the color translation table"),
                format!(
                    "Add a row for '{color}' in the Platform Binding Color Translation table in ai-agents.md"
                ),
            ));
        }
    }
    if seen_colors.is_empty() {
        checks.push(ValidationCheck::passed(
            "Color translation map",
            "No agent color values to verify (no agents or all use theme tokens)",
        ));
    }

    // §5b: capability-tier map
    for tier in &seen_tiers {
        let needle = format!("`{tier}`");
        if tier_map.contains(&needle) || tier_map.contains(&format!("model: {tier}")) {
            checks.push(ValidationCheck::passed(
                format!("Tier mapping: {tier}"),
                format!("'{tier}' is mapped in model-selection.md"),
            ));
        } else {
            checks.push(ValidationCheck::failed(
                format!("Tier mapping: {tier}"),
                "model value mapped in repo-governance/development/agents/model-selection.md",
                format!("'{tier}' is NOT in the capability-tier map"),
                format!(
                    "Add a row for '{tier}' in the capability-tier table in model-selection.md"
                ),
            ));
        }
    }
    if seen_tiers.is_empty() {
        checks.push(ValidationCheck::passed(
            "Capability-tier map",
            "No agent model values to verify (all agents use planning-grade inherit)",
        ));
    }

    checks
}

/// Check that the committed file at `binding.rel_path` has the exact expected bytes.
fn validate_binding_file(repo_root: &Path, binding: &BindingFile) -> ValidationCheck {
    let check_name = format!("Binding: {}", binding.rel_path);
    let abs = join_rel(repo_root, &binding.rel_path);

    match fs::read(&abs) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => ValidationCheck::failed(
            check_name,
            "file present and byte-equal to generated content",
            "file missing",
            format!(
                "{} is missing; run `rhino-cli agents emit-bindings`",
                binding.rel_path
            ),
        ),
        Err(e) => ValidationCheck::failed_msg(
            check_name,
            format!("failed to read {}: {e}", binding.rel_path),
        ),
        Ok(actual) => {
            if actual == binding.content.as_bytes() {
                ValidationCheck::passed(
                    check_name,
                    format!("{} matches generated content", binding.rel_path),
                )
            } else {
                ValidationCheck::failed(
                    check_name,
                    "byte-equal to generated content",
                    "content differs from generated bytes",
                    format!(
                        "{} drifted from canonical content; run `rhino-cli agents emit-bindings`",
                        binding.rel_path
                    ),
                )
            }
        }
    }
}

/// Check that `dir` is referenced in the platform-bindings catalog when it exists on disk.
fn validate_catalog_coverage(repo_root: &Path, dir: &str) -> ValidationCheck {
    let check_name = format!("Catalog Coverage: {dir}");
    let dir_path = repo_root.join(strip_leading_slash(dir));

    if !dir_path.exists() {
        return ValidationCheck::passed(
            check_name,
            format!("{dir} absent on disk; no catalog row required"),
        );
    }

    let catalog_path = join_rel(repo_root, PLATFORM_BINDINGS_CATALOG);
    let catalog = match fs::read_to_string(&catalog_path) {
        Ok(c) => c,
        Err(e) => {
            return ValidationCheck::failed_msg(
                check_name,
                format!("failed to read {PLATFORM_BINDINGS_CATALOG}: {e}"),
            );
        }
    };

    if catalog.contains(dir) {
        ValidationCheck::passed(
            check_name,
            format!("{dir} referenced in {PLATFORM_BINDINGS_CATALOG}"),
        )
    } else {
        ValidationCheck::failed(
            check_name,
            format!("{dir} referenced in {PLATFORM_BINDINGS_CATALOG}"),
            format!("{dir} present on disk but absent from catalog"),
            format!(
                "binding dir {dir} exists but is not referenced in {PLATFORM_BINDINGS_CATALOG}; add a catalog row"
            ),
        )
    }
}

/// Check that the non-standard `.codex/agents/` directory does not exist.
/// Codex CLI configures agents via `agents.<name>` sub-tables in
/// `.codex/config.toml`, not via a directory of agent files.
fn validate_no_codex_agents_dir(repo_root: &Path) -> ValidationCheck {
    let check_name = "No Codex Agents Dir: .codex/agents".to_string();
    let dir_path = join_rel(repo_root, ".codex/agents");

    if dir_path.exists() {
        ValidationCheck::failed(
            check_name,
            ".codex/agents absent",
            ".codex/agents present on disk",
            ".codex/agents/ is not an official Codex CLI convention; define agents as \
             `agents.<name>` sub-tables in .codex/config.toml and delete the directory"
                .to_string(),
        )
    } else {
        ValidationCheck::passed(
            check_name,
            ".codex/agents absent; Codex CLI agents configured via config.toml sub-tables"
                .to_string(),
        )
    }
}

/// Joins a POSIX-style relative path onto the repo root for the host FS.
fn join_rel(repo_root: &Path, rel: &str) -> PathBuf {
    let mut path = repo_root.to_path_buf();
    for segment in rel.split('/') {
        if !segment.is_empty() {
            path.push(segment);
        }
    }
    path
}

/// Strip a leading `/` from `s` if present, to allow safe `Path::join`.
fn strip_leading_slash(s: &str) -> &str {
    s.strip_prefix('/').unwrap_or(s)
}

