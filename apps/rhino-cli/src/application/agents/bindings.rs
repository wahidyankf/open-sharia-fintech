/// Relative path of the Amazon Q rules pointer file (POSIX separators; joined
/// onto the repo root for the host filesystem).
pub const AMAZONQ_RULES_POINTER: &str = ".amazonq/rules/00-agents-md.md";

/// Relative directory for generated Amazon Q agent definitions.
pub const AMAZONQ_AGENT_DEFINITION_DIR: &str = ".amazonq/cli-agents";

/// Deterministic content of the Amazon Q rules pointer file.
const RULES_POINTER_CONTENT: &str = "# Project Instructions Pointer\n\nThe canonical instructions for this repository live in `AGENTS.md` at the repository root.\nRead and follow `AGENTS.md`. This file exists because Amazon Q Developer does not yet read\n`AGENTS.md` natively; the default agent configuration loads `AGENTS.md` via its `resources`.\n\nDo not edit this file by hand — it is generated by `rhino-cli agents emit-bindings`.\n";

