type Confidence = "high" | "moderate" | "proxy";
type Track = "ic" | "mgmt";
export type EngRole =
  | "swe_1"
  | "swe_2"
  | "senior_swe"
  | "eng_manager"
  | "staff_swe"
  | "senior_eng_manager"
  | "senior_staff_swe"
  | "director"
  | "principal_swe"
  | "senior_director"
  | "distinguished_swe"
  | "vp_eng"
  | "fellow"
  | "svp_eng"
  | "cto";

type SalaryPoint = {
  monthlyGrossLocal: number;
  confidence: Confidence;
  note?: string;
};

type RoleSalaryDistribution = {
  p25: SalaryPoint;
  median: SalaryPoint;
  p75: SalaryPoint;
  nonSalaryComp: { annualLocal: number; confidence: Confidence; note?: string };
};

export type RoleMeta = {
  role: EngRole;
  rank: number;
  track: Track;
  label: { en: string; id: string };
};

export type RoleMatrix = {
  snapshotDate: string;
  ladder: RoleMeta[];
  salaries: Record<string, Record<EngRole, RoleSalaryDistribution>>;
};

function sp(monthlyGrossLocal: number, confidence: Confidence, note?: string): SalaryPoint {
  return { monthlyGrossLocal, confidence, note };
}

function dist(
  p25: SalaryPoint,
  median: SalaryPoint,
  p75: SalaryPoint,
  nonSalaryAnnual: number,
  nonSalaryConf: Confidence,
  nonSalaryNote?: string,
): RoleSalaryDistribution {
  return {
    p25,
    median,
    p75,
    nonSalaryComp: {
      annualLocal: nonSalaryAnnual,
      confidence: nonSalaryConf,
      note: nonSalaryNote,
    },
  };
}

